// AuthCalloutConfig wires the broker as an auth_callout service.
//
//   - BrokerNkeySeed: user nkey seed the broker uses to CONNECT to NATS.
//     Must be in the NATS server's Options.AuthCallout.AuthUsers list so the
//     broker bypasses auth_callout itself; must also be a static
//     Options.Nkeys entry so the connection has permissions to subscribe
//     to $SYS.REQ.USER.AUTH and to broker business subjects.
//   - AccountSeed: account nkey seed the broker uses to sign user JWTs in
//     auth_callout responses. Must equal the public key configured at
//     Options.AuthCallout.Issuer.
//
// Both seeds are owned (and Wipe'd) by the broker process. For prod they
// would be loaded from disk; for tests they're generated by the test
// harness and passed in here.
type AuthCalloutConfig = xferauth.CalloutConfig

// connectOpts builds the nats.Options the broker uses for its own connection. The
// option builder and its gotcha #89 / private-inbox rationale moved verbatim to
// infraattach.BrokerOptions, beside the S9 descriptor that now owns every dial.
// origin: hot-update S9 plan §4.4 / P22
func (b *Broker) brokerConnectOptions() ([]nats.Option, string, error) {
	return infraattach.CalloutOptions(b.cfg.Logger, b.cfg.AuthCallout)
}

// brokerInfraConnect is the ONE connection root for cold Run and the S6 restored
// graph, and publishes its NC; ordinary reconnect is the same owner's gated Dial.
// The audit cursor reads the current Node at call time: a returned cut replaces b.cl.
// origin: hot-update S9 plan §4.4 / T48; rv-business F2 / rv-infra F10
func brokerInfraConnect(b *Broker, deadline controlbudget.Deadline) error {
	if b.infra == nil {
		owner, err := infraattach.NewBrokerFromStore(b.read().SQL(), infraattach.BrokerConfig{URL: b.cfg.NATSURL, Logger: b.cfg.Logger,
			Options: b.brokerConnectOptions, Infra: b.cfg.Infra, AuditCursor: func() (uint64, bool, error) {
				if b.cl == nil || b.cl.node == nil {
					return 0, false, nil
				}
				v, err := b.cl.node.AuditPublishedIndex()
				return v, true, err
			}})
		if err != nil {
			return err
		}
		b.infra = owner
	}
	nc, err := b.infra.Connect(deadline)
	b.nc.Store(nc) // nil on error: both callers start from an empty slot
	return err
}

// installAuthCallout subscribes to $SYS.REQ.USER.AUTH on the broker's
// existing NATS connection, dispatching each request to authcallout.Handler.
// Returns the subscription so the caller can Unsubscribe on shutdown.
func (b *Broker) installAuthCallout(nc *nats.Conn, imageOwners ...*brokerAuthOwner) (*nats.Subscription, error) {
	if b.cfg.AuthCallout == nil {
		return nil, nil
	}
	accountKp, err := nkeys.FromSeed(b.cfg.AuthCallout.AccountSeed)
	if err != nil {
		return nil, fmt.Errorf("broker: parse account seed: %w", err)
	}
	// The subscription's close callback joins both Handle and forwarded PIN
	// verification before wiping the signing key. A timeout never wipes a key
	// still borrowed by an in-flight response.
	// origin: hot-update S6 plan §8.1 / T29
	owner := newBrokerAuthOwner(b, 0)
	if len(imageOwners) != 0 && imageOwners[0] != nil {
		owner = imageOwners[0]
	}
	owner.Key = accountKp

	h := &authcallout.Handler{
		Settlement: brokerTransferVerifier(b),
		// Reloaded managed $SYS principals (S9 P12 / S7 lead R8) come from the loaded file.
		SystemPrincipals: brokerSystemPrincipals(b),
		DB:               b.cfg.DB,
		AccountKp:        accountKp,
		Now:              b.cfg.Now,
		Logger:           b.cfg.Logger,
		EmitEvent:        b.pubSysEvent,  // P7: member_joined / pin_failed → events stream
		JWTTTL:           24 * time.Hour, // Publish initialized defaults before the isolated probe can run concurrently.
	}

	// D9 round-1 BLOCKER: in cluster mode the handler's DB is the READ-ONLY FSM handle, so
	// the default ProvisionWithPIN(h.DB)/JoinWithPIN(h.DB) direct writes would fail (and
	// bypass raft). Route the PIN provision/join writes through the leader (Propose-local /
	// follower-forward) via the D4 seams. The forwarder was built in Run before this call.
	if b.clusterMode {
		if b.cl == nil || b.cl.node == nil || b.cl.forwarder == nil || b.cl.forwarder.nc != nc || b.read().SQL() != b.cl.node.RODB() {
			accountKp.Wipe()
			return nil, fmt.Errorf("broker: current cluster auth dependencies are not bound")
		}
		// PUBLISH THE BUDGETED VERIFIER BEFORE THE SEAMS USE IT. Both clustered PIN paths
		// must run Argon2 through the process-wide ceiling of whichever broker actually
		// spends the CPU: the leader-local branch takes it as an argument here, and the
		// FORWARDED branch — whose responder was subscribed earlier in the cluster bring-up,
		// before this handler existed — reads it back through b.leaderPINVerify.
		// origin: prerelease audit external review M-1.
		verifyPIN := func(pin, hash string) error {
			if !owner.Enter() {
				return errPINVerifierUnwired
			}
			defer owner.Leave()
			return h.VerifyPINWithBudget(pin, hash)
		}
		owner.Verifier = &verifyPIN
		b.leaderPINVerify.Store(&verifyPIN)
		h.ProvisionAgentWrite = NewProvisionSeam(b.cl.node, b.cl.forwarder, verifyPIN)
		h.JoinMemberWrite = NewJoinSeam(b.cl.node, b.cl.forwarder, verifyPIN)
		h.LeaderContactStale = b.cl.node.LeaderContactStale
		// batch B / B3: make the seam-nil fallbacks fail CLOSED. Until now this `if` was the
		// entire enforcement of "clustered ⇒ both seams wired"; a third write path added with its
		// own seam, or a refactor that moved this block, would silently fall back to writing the
		// read-only FSM handle on the authentication path. Setting this LAST, alongside the seams,
		// keeps the three in one place — and internal/broker's wiring guard test asserts they stay
		// together.
		h.ClusterMode = true
	}

	handleAuth := authcallout.WithInfraManager(h, func(target string) bool { return target == b.selfID })

	// QueueSubscribe (not Subscribe) so that in a ≥2-node cluster exactly ONE
	// broker answers each callout — every broker shares the "tether-authcallout"
	// queue group (§6.2), and a request raised on server A can be answered by
	// broker B over the routes. At N=1 a one-member queue group behaves identically
	// to a plain subscription (zero regression).
	handle := func(msg *nats.Msg) {
		if !owner.Enter() {
			return
		}
		defer owner.Leave()
		respJWT, err := handleAuth(string(msg.Data))
		if err != nil {
			b.cfg.Logger.Warn("authcallout: handle failed", "err", err)
			return
		}
		owner.ObserveProbe(string(msg.Data), respJWT)
		if msg.Reply != "" {
			// h1 A2 egress exemption (the ONE bare Respond outside respondLogged,
			// pinned by reply_egress_test.go): the consumer is nats-server's
			// auth-callout machinery, which expects a signed JWT or nothing — a
			// JSON reply_too_large fallback would be garbage to it, and the JWT
			// is structurally far below any max_payload. Errors here are already
			// surfaced by the server itself as an auth timeout.
			if err := msg.Respond([]byte(respJWT)); err != nil {
				b.cfg.Logger.Warn("authcallout: response delivery failed", "err", err)
			} else if now, err := procrequest.BootNow(); err == nil {
				owner.Mu.Lock()
				owner.LastReplyBootNS = now
				owner.Mu.Unlock()
			}
		}
	}
	owner.HandleProbe = handle
	if b.infra.Configured() {
		// S9 owns the normal queue on its auth-only NC. This business NC must not
		// carry it, or an SDK reconnect would replay auth beside business SUBs.
		// origin: hot-update S9 plan §4.4 / T48; rv-business F2 / rv-infra F10
		var stop <-chan struct{} // Run's cancellation ends a cold admission wait early.
		if b.runCtx != nil {
			stop = b.runCtx.Done()
		}
		receipt, err := b.infra.Arm(infraattach.AuthHandle(owner.Enter, owner.Leave, handleAuth), infraattach.AuthReplied(owner.ObserveProbe, &owner.Mu, &owner.LastReplyBootNS), owner.Deadline, stop)
		if owner.SubFlushBootNS = receipt.AuthPONG; err == nil && owner.Deadline != 0 {
			emitBrokerImageEvent(b, "auth_sub_flush", owner.SubFlushBootNS)
		}
		return nil, err
	}
	sub, err := nc.QueueSubscribe("$SYS.REQ.USER.AUTH", "tether-authcallout", handle)
	if err != nil {
		owner.Fence()
		owner.Finish()
		return nil, fmt.Errorf("broker: queue-subscribe $SYS.REQ.USER.AUTH: %w", err)
	}
	owner.Sub = sub
	sub.SetClosedHandler(func(string) {
		owner.Fence()
		owner.Finish()
	})
	// QueueSubscribe only buffers SUB. Auth cannot become usable until the
	// local server acknowledges it; late business wiring has its own barrier.
	// origin: hot-update S6 plan §8.1 / T29
	timeout, err := brokerAuthRemaining(owner.Deadline)
	if err == nil && !sub.IsValid() {
		err = nats.ErrConnectionClosed
	}
	if err == nil {
		err = nc.FlushTimeout(timeout)
	}
	if err != nil {
		return nil, errors.Join(fmt.Errorf("broker: auth subscription flush: %w", err), stopBrokerImageAuth(owner, owner.Deadline))
	}
	if owner.Deadline != 0 {
		owner.SubFlushBootNS, err = procrequest.BootNow()
		if err != nil {
			owner.Fence()
			_ = sub.Unsubscribe()
			return nil, err
		}
		emitBrokerImageEvent(b, "auth_sub_flush", owner.SubFlushBootNS)
	}
	return sub, nil
}

// verifyPINOnLeader is forwardDeps.verifyPIN for the cluster.apply responder: the budgeted
// Argon2 verifier of the auth_callout handler running in THIS process, resolved at call
// time because the responder is subscribed before that handler is built.
//
// A nil load means a forwarded PIN write arrived before (or without) the handler being
// installed. That refusal is retriable and costs one join attempt; running Argon2 anyway
// would restore exactly the unmetered CPU oracle this plumbing removes.
//
// A package-level function taking *Broker, not a method: the structural-budget ratchet pins
// this type's method count EXACTLY, and it caught the 286th on the first run.
// origin: prerelease audit external review M-1.
func verifyPINOnLeader(b *Broker, pin, hash string) error {
	fn := b.leaderPINVerify.Load()
	if fn == nil {
		return errPINVerifierUnwired
	}
	return (*fn)(pin, hash)
}

func newBrokerAuthOwner(b *Broker, deadline controlbudget.Deadline) *brokerAuthOwner {
	idle := make(chan struct{})
	close(idle)
	// A cold idle barrier can exist before a broker has been bound. Preserve
	// that constructor behavior while borrowing the verifier slot only when present.
	// origin: hot-update S6 plan §8.1 / T29 / BROKER-SLIM
	var verifierOwner *atomic.Pointer[func(string, string) error]
	if b != nil {
		verifierOwner = &b.leaderPINVerify
	}
	return &brokerAuthOwner{VerifierOwner: verifierOwner, Emit: func(event string, now int64) { emitBrokerImageEvent(b, event, now) }, Deadline: deadline, Idle: idle, Done: make(chan struct{})}
}

// P11 calls this after currentDB/forwarder/apply responders exist and before any
// business subscription or public Accept resumes. The disposable unactivated
// identity reads no provisioning state and writes nothing. The temporary
// local observer proves this owner even when the shared queue chooses a peer.
// origin: hot-update S6 plan §8.1 / T29
func startBrokerImageAuth(b *Broker, nc *nats.Conn, deadline controlbudget.Deadline) (*brokerAuthOwner, error) {
	if deadline == 0 {
		return nil, fmt.Errorf("broker: image auth requires an absolute deadline")
	}
	if b == nil || nc == nil || b.read().SQL() == nil || b.cfg.AuthCallout == nil {
		return nil, fmt.Errorf("broker: image auth requires current connection and auth_callout")
	}
	if _, err := brokerAuthRemaining(deadline); err != nil {
		return nil, err
	}
	owner := newBrokerAuthOwner(b, deadline)
	if _, err := b.installAuthCallout(nc, owner); err != nil {
		return owner, errors.Join(err, stopBrokerImageAuth(owner, deadline))
	}
	if err := probeBrokerImageAuth(owner, nc, deadline); err != nil {
		return owner, errors.Join(err, stopBrokerImageAuth(owner, deadline))
	}
	if _, err := brokerAuthRemaining(deadline); err != nil {
		return owner, errors.Join(err, stopBrokerImageAuth(owner, deadline))
	}
	usableBootNS, err := procrequest.BootNow()
	if err != nil {
		return owner, errors.Join(err, stopBrokerImageAuth(owner, deadline))
	}
	owner.UsableBootNS = usableBootNS
	emitBrokerImageEvent(b, "auth_reply", owner.ReplyBootNS)
	emitBrokerImageEvent(b, "auth_usable", owner.UsableBootNS)
	return owner, nil
}

// One payload-free record shape is shared by every phase producer. BOOTTIME
// comes from the broker itself; the collector must preserve it rather than
// assigning the time it happened to poll the log. No JWT or credential is logged.
// origin: hot-update S6 plan §8.1 / rv-ctl-3
func emitBrokerImageEvent(b *Broker, event string, bootNS int64) {
	if b == nil || b.cfg.Logger == nil {
		return
	}
	if bootNS == 0 {
		var err error
		bootNS, err = procrequest.BootNow()
		if err != nil {
			return
		}
	}
	cutID := "boot"
	if b.imageControl != nil && b.imageControl.cutID != "" {
		cutID = b.imageControl.cutID
	}
	b.cfg.Logger.Info("broker: image phase", "cut_id", cutID, "event", event, "phase", event, "boot_ns", bootNS)
}

