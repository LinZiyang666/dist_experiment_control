// origin: upgrade-safety internal review S5 — smokeVersion had zero direct
// tests while its doc comment claimed "pinned by test", and the emitter
// (cmd/tether newVersionCmd) and this parser are two literals in different
// RELEASES of the binary: an N-1 agent parses the line printed by the N
// binary it is installing. Both sides now derive from proto.VersionLine;
// TestSmokeVersionParsesTheRealVersionLine is the cross-seam nail.

func writeScript(t *testing.T, body string) string {
	t.Helper()
	p := filepath.Join(t.TempDir(), "candidate")
	if err := os.WriteFile(p, []byte(body), 0o755); err != nil {
		t.Fatal(err)
	}
	return p
}

func TestSmokeVersionParsesTheRealVersionLine(t *testing.T) {
	// The exact first line a real tether binary prints, generated by the
	// same helper newVersionCmd uses — if VersionLine's shape drifts from
	// what strings.Fields(line)[1] extracts, this fails before a release
	// strands the fleet.
	p := writeScript(t, "#!/bin/sh\necho '"+proto.VersionLine()+"'\n")
	got, err := smokeVersion(p)
	if err != nil {
		t.Fatalf("smokeVersion on the real version line: %v", err)
	}
	if got != proto.ReleaseVersion {
		t.Fatalf("smokeVersion = %q, want %q — the --wait equality criterion is broken", got, proto.ReleaseVersion)
	}
}

func TestSmokeVersionTable(t *testing.T) {
	cases := []struct {
		name    string
		body    string
		want    string
		wantErr bool
	}{
		{"plain_tag", "#!/bin/sh\necho 'tether v1.2.3 (proto v2)'\n", "v1.2.3", false},
		// origin: upgrade-safety external review F4 — the artifact's epoch
		// must match the running agent. UpgradeReq.ProtoVersion authenticates
		// only ctl/broker compatibility; it says nothing about the downloaded
		// bytes. Accepting a proto-v3 artifact here installs a binary that the
		// v2 broker must reject, bypassing `proto_bump_requires_reinstall`.
		{"different_proto_epoch", "#!/bin/sh\necho 'tether v1.2.3 (proto v3)'\n", "", true},
		// Adversarial: prints a perfectly good line, then exits non-zero —
		// a binary that can print but cannot run must NOT pass the gate.
		{"prints_then_exits_nonzero", "#!/bin/sh\necho 'tether v1.2.3 (proto v2)'\nexit 1\n", "", true},
		{"wrong_prefix", "#!/bin/sh\necho 'NEW-AGENT-V9'\n", "", true},
		{"tag_only_no_prefix", "#!/bin/sh\necho 'v1.2.3'\n", "", true},
		{"empty_output", "#!/bin/sh\nexit 0\n", "", true},
		// Leading blank lines are skipped; the first non-empty line decides.
		{"leading_blank_lines", "#!/bin/sh\necho ''\necho 'tether v9.9.9 (proto v2)'\n", "v9.9.9", false},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			got, err := smokeVersion(writeScript(t, c.body))
			if c.wantErr {
				if err == nil {
					t.Fatalf("smokeVersion = %q, want error", got)
				}
				return
			}
			if err != nil || got != c.want {
				t.Fatalf("smokeVersion = (%q, %v), want (%q, nil)", got, err, c.want)
			}
		})
	}
}

func TestSmokeVersionRefusesNonExecutable(t *testing.T) {
	p := filepath.Join(t.TempDir(), "candidate")
	if err := os.WriteFile(p, []byte("just bytes, not a binary"), 0o644); err != nil {
		t.Fatal(err)
	}
	if got, err := smokeVersion(p); err == nil {
		t.Fatalf("smokeVersion = %q, want exec error for a non-executable file", got)
	}
}

// origin: internal review S20 — the hardlink-refusing-filesystem fallback for
// the prev slot. plan §10.2 named this branch as an external-review check
// item; it had zero coverage.
func TestCopyFilePreservesContentAndExecutableMode(t *testing.T) {
	dir := t.TempDir()
	src := filepath.Join(dir, "src")
	dst := filepath.Join(dir, "dst")
	if err := os.WriteFile(src, []byte("BINARY-BYTES"), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := copyFile(src, dst); err != nil {
		t.Fatal(err)
	}
	got, err := os.ReadFile(dst)
	if err != nil || string(got) != "BINARY-BYTES" {
		t.Errorf("copy content = %q err=%v", string(got), err)
	}
	fi, err := os.Stat(dst)
	if err != nil {
		t.Fatal(err)
	}
	if fi.Mode().Perm() != 0o755 {
		t.Errorf("copied prev slot mode = %o, want 0755 (a non-executable prev cannot be exec'd back into)", fi.Mode().Perm())
	}
}
