package natsconf

import (
	"os"
	"path/filepath"
	"testing"
)

func writeConf(t *testing.T, body string) string {
	t.Helper()
	p := filepath.Join(t.TempDir(), "nats.conf")
	if err := os.WriteFile(p, []byte(body), 0o600); err != nil {
		t.Fatal(err)
	}
	return p
}

// installSHConf is the EXACT shape install.sh:673-687 writes (host+port, NOT a listen key;
// jetstream store_dir; websocket no_tls). The takeover MUST accept it + harvest the client
// listen from host+port.
const installSHConf = `# tether nats-server config (generated by install.sh)
host: "127.0.0.1"
port: 4222

jetstream {
  store_dir: "/var/lib/tether/jetstream"
}

websocket {
  host: "127.0.0.1"
  port: 8222
  no_tls: true
}
`

func TestPreflightAcceptsInstallShape(t *testing.T) {
	own, err := Preflight(writeConf(t, installSHConf))
	if err != nil {
		t.Fatalf("install.sh conf must pass preflight, got: %v", err)
	}
	// host+port harvest to the client listen (install.sh writes no `listen` key).
	if got := own.ClientListen(); got != "127.0.0.1:4222" {
		t.Fatalf("ClientListen = %q, want 127.0.0.1:4222 (harvested from host+port)", got)
	}
	// All four directives classify InstallSafe.
	for _, e := range own.Entries {
		if e.Bucket != InstallSafe {
			t.Errorf("%s classified %s, want install_safe", e.Key, e.Bucket)
		}
	}
}

func TestPreflightRefusesUnknownDirective(t *testing.T) {
	for _, body := range []string{
		installSHConf + "\naccounts { A { users: [{user: u}] } }\n",
		installSHConf + "\nleafnodes { remotes: [] }\n",
		installSHConf + "\nmqtt { port: 1883 }\n",
		installSHConf + "\ngateway { name: g }\n",
	} {
		if _, err := Preflight(writeConf(t, body)); err == nil {
			t.Fatalf("an unknown directive must be refused (fail-closed); conf:\n%s", body)
		}
	}
}

func TestPreflightPreservesTuningPassthrough(t *testing.T) {
	// usage.md:970 documents raising max_payload for tier-A transfer — it must NOT be
	// refused (a hard-refuse would brick every file-transfer broker).
	own, err := Preflight(writeConf(t, installSHConf+"\nmax_payload: 16777216\n"))
	if err != nil {
		t.Fatalf("max_payload (documented tuning) must pass, got: %v", err)
	}
	found := false
	for _, e := range own.Entries {
		if e.Key == "max_payload" {
			if e.Bucket != TetherPassthrough {
				t.Errorf("max_payload classified %s, want tether_passthrough", e.Bucket)
			}
			found = true
		}
	}
	if !found {
		t.Fatal("max_payload not in the ownership table")
	}
}

func TestPreflightRefusesInclude(t *testing.T) {
	if _, err := Preflight(writeConf(t, "include \"extra.conf\"\n"+installSHConf)); err == nil {
		t.Fatal("an `include` must be refused (split-file confs can't be safely round-tripped)")
	}
}

func TestPreflightClassifiesOperatorAuth(t *testing.T) {
	// The §3.4 hand-added authorization{} block — recognized (read for identity), not unknown.
	body := installSHConf + `
authorization {
  users: [{ nkey: "UBROKERPUB" }]
  auth_callout {
    issuer: "UACCOUNTPUB"
    auth_users: [ "UBROKERPUB" ]
  }
}
`
	own, err := Preflight(writeConf(t, body))
	if err != nil {
		t.Fatalf("a §3.4 authorization block must be recognized, got: %v", err)
	}
	found := false
	for _, e := range own.Entries {
		if e.Key == "authorization" {
			if e.Bucket != OperatorAuth {
				t.Errorf("authorization classified %s, want operator_auth", e.Bucket)
			}
			found = true
		}
	}
	if !found {
		t.Fatal("authorization not in the ownership table")
	}
}
