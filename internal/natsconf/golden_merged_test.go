// golden_merged_test.go — the fleet control for B5 (T0).
//
// WHY A GOLDEN, AND WHY OVER *THIS* FUNCTION
// ------------------------------------------
// B5 restructures how a nats.conf is assembled. The only thing that matters to a running broker is the
// BYTES that land in /etc/tether/nats.d/nats.conf, and those bytes are BuildMergedConf's output — not
// Render's. The merge layer adds the routes-mTLS / listen / cluster-name harvest, the monitor
// harvest, the re-emitted websocket{} block and the sorted tuning passthrough. A golden taken at the
// Render level is structurally blind to every one of those, and the resolution layer is precisely what
// B5 moves. So a Render-level golden would pass while the conf on the fleet's only broker changed.
//
// HOW TO READ A FAILURE
// --------------------
// A diff here means the rendered conf CHANGED. That is not automatically wrong — but it is never
// incidental: the reconciler compares the on-disk conf to its render byte-for-byte
// (natsreconcile: `if string(current) == merged`), so any change makes the next tick swap the conf and
// SIGHUP the server on every broker in the fleet. If the change is intended, update the golden IN THE
// SAME COMMIT and say in the message what the operator will observe.
//
// THE FIXTURES ARE THE POINT
// -------------------------
// racknerdShapeConf is the shape the fleet's only broker actually runs: force-singled and then HAND
// DE-CLUSTERED during the 2026-07-04 incident — standalone JetStream, no cluster{} block, monitor
// present, websocket block from install.sh. Every drill starts from a clustered or a freshly-installed
// node, so this shape is covered at the deploy tier by NOTHING. It is here because it is the one that
// cannot be allowed to change.
func TestMergedConfGoldenBytes(t *testing.T) {
	for _, tc := range goldenCases(t) {
		t.Run(tc.name, func(t *testing.T) {
			own, err := Preflight(writeConf(t, tc.liveConf))
			if err != nil {
				t.Fatalf("fixture must preflight clean (else the golden proves nothing): %v", err)
			}
			got, err := BuildMergedConf(own, tc.cfg(own))
			if err != nil {
				t.Fatalf("BuildMergedConf: %v", err)
			}
			// NO normalisation, deliberately. An earlier version ran
			// `strings.ReplaceAll(got, t.TempDir(), "<TMP>")` here, which was a no-op twice over: every
			// t.TempDir() call returns a NEW directory, so the needle was a path that appears nowhere in
			// got; and none of these fixtures puts a temp path in the output anyway (JSStoreDir is
			// /var/lib/tether/js in all four). It read as a safeguard that was doing something, which is
			// worse than no safeguard — the next person to add a fixture with a real temp path in it would
			// have trusted it. If one is ever needed, capture the dir in a variable and replace THAT.
			compareGolden(t, tc.name, got)
		})
	}
}

type goldenCase struct {
	name     string
	liveConf string
	cfg      func(*Ownership) Config
}

