func goldenCases(t *testing.T) []goldenCase {
	t.Helper()
	// A fixed peer set: golden stability requires deterministic identities, and Render sorts peers by
	// ServerName so the order here is not load-bearing.
	peers := []Broker{
		{ServerName: "brk-a", NkeyPub: "UBUSNKEYA", RouteURL: "nats://10.0.0.1:6222"},
		{ServerName: "brk-b", NkeyPub: "UBUSNKEYB", RouteURL: "nats://10.0.0.2:6222"},
	}
	self := peers[0]
	const acct = "ABROKERACCOUNTPUB"

	return []goldenCase{
		{
			// The reconciler's own render over the live fleet shape: standalone stays standalone (it never
			// crosses the destructive boundary on its own), everything harvested.
			name:     "reconciler-over-racknerd-shape",
			liveConf: racknerdShapeConf,
			cfg: func(own *Ownership) Config {
				return Config{
					Standalone:    true,
					Local:         Broker{ServerName: "brk-racknerd", NkeyPub: "UBUSNKEYA"},
					Peers:         []Broker{{ServerName: "brk-racknerd", NkeyPub: "UBUSNKEYA"}},
					AccountIssuer: acct,
					JSStoreDir:    own.JSStoreDir(),
					ClientListen:  own.ClientListen(),
				}
			},
		},
		{
			// The reconciler over a VOTER: no cert paths supplied, so the mTLS identity + route listen +
			// cluster name all come from the harvest. This is the path that would break silently if the
			// harvest moved.
			name:     "reconciler-over-clustered-shape",
			liveConf: clusteredShapeConf,
			cfg: func(own *Ownership) Config {
				return Config{
					Local:         self,
					Peers:         peers,
					AccountIssuer: acct,
					JSStoreDir:    own.JSStoreDir(),
					ClientListen:  own.ClientListen(),
				}
			},
		},
		{
			// The grow cutover: forces the monitor and supplies the secrets-dir mTLS identity, over a live
			// conf that is still standalone JS (no cluster{} to harvest from).
			name:     "grow-cutover-over-racknerd-shape",
			liveConf: racknerdShapeConf,
			cfg: func(own *Ownership) Config {
				return Config{
					Local:         self,
					Peers:         peers,
					AccountIssuer: acct,
					JSStoreDir:    own.JSStoreDir(),
					ClientListen:  own.ClientListen(),
					MonitorListen: "127.0.0.1:8223",
					CAFile:        "/etc/tether/secrets/cluster-ca.pem",
					CertFile:      "/etc/tether/secrets/route-cert.pem",
					KeyFile:       "/etc/tether/secrets/route-key.pem",
					ClusterListen: "0.0.0.0:6222",
				}
			},
		},
		{
			// Offline force-single / --to-standalone: standalone by INTENT over a clustered conf. This is
			// the destructive transition, and its bytes decide whether the JS store is orphaned.
			name:     "force-single-over-clustered-shape",
			liveConf: clusteredShapeConf,
			cfg: func(own *Ownership) Config {
				solo := Broker{ServerName: "brk-a", NkeyPub: "UBUSNKEYA"}
				return Config{
					Standalone:    true,
					Local:         solo,
					Peers:         []Broker{solo},
					AccountIssuer: acct,
					JSStoreDir:    own.JSStoreDir(),
					ClientListen:  own.ClientListen(),
					MonitorListen: own.MonitorHTTP(),
				}
			},
		},
	}
}

// compareGolden compares got against testdata/<name>.conf. A MISSING golden is created and the test
// FAILS, rather than passing silently: a golden that writes itself on first run accepts whatever the code
// happens to do, which is the opposite of a control.
func compareGolden(t *testing.T, name, got string) {
	t.Helper()
	path := filepath.Join("testdata", name+".conf")
	want, err := os.ReadFile(path)
	if os.IsNotExist(err) {
		if mkErr := os.MkdirAll("testdata", 0o755); mkErr != nil {
			t.Fatalf("create testdata: %v", mkErr)
		}
		if wErr := os.WriteFile(path, []byte(got), 0o644); wErr != nil {
			t.Fatalf("write golden: %v", wErr)
		}
		t.Fatalf("golden %s did not exist and has been CREATED — review it, confirm it is the conf you "+
			"intend brokers to run, and re-run. It is not accepted until a human has read it.", path)
	}
	if err != nil {
		t.Fatalf("read golden %s: %v", path, err)
	}
	if string(want) != got {
		t.Errorf("the rendered nats.conf CHANGED for %s.\n"+
			"The reconciler compares the on-disk conf to its render byte-for-byte, so any change here makes "+
			"the next tick swap the conf and SIGHUP nats-server on every broker in the fleet. If that is "+
			"intended, update testdata/%s.conf in the SAME commit and say so in the message.\n"+
			"--- want ---\n%s\n--- got ---\n%s", name, name, want, got)
	}
}
