// broker's actual shape since the 2026-07-04 incident.
const alreadyStandaloneConf = `# tether nats-server config (generated by install.sh)
server_name: "brk-solo"
host: "0.0.0.0"
port: 4222
http: "127.0.0.1:8223"
jetstream {
  store_dir: "/var/lib/tether/js"
}
authorization {
  auth_callout {
    issuer: "ABROKERACCOUNTPUB"
    account: "$G"
    auth_users: [ "UBUSNKEYA" ]
  }
  users: [
    { nkey: "UBUSNKEYA" }
  ]
}
`

// decluster_idempotence_test.go — offline de-cluster on an ALREADY-standalone conf must touch NOTHING
// (B5, critique B5-C4).
//
// WHY THIS IS THE ONE TO PIN
// --------------------------
// deClusterStandaloneConf's already-standalone branch carries a comment in capitals: "no-op — already
// standalone: no render, no swap, NO destructive JS-store reset". Drop that branch, or move it below the
// render, and `tether cluster force-single` on a survivor that is ALREADY hand-de-clustered re-renders,
// re-swaps, and walks into the JS-store reset path.
//
// That input is not hypothetical. The fleet's only broker is exactly that shape: force-singled and then
// hand de-clustered during the 2026-07-04 incident. And the deploy tier cannot catch it — drill 20 starts
// from a CLUSTERED survivor, so the already-standalone arm is exercised by no drill at all.
//
// The assertion is deliberately about the FILESYSTEM rather than about the return values: "changed=false"
// is what the function says, while "no .bak appeared and the mtime did not move" is what the operator's
// disk says. A refactor can preserve the former while breaking the latter.
//
// WHICH ASSERTION ACTUALLY FIRES — AND WHY THIS TEST CARRIES A REAL DB
// --------------------------------------------------------------------
// An earlier version of this test passed a dbPath that pointed at nothing, on the reasoning that the
// no-op branch returns before readSelfIdentity so a missing DB must not matter. Mutation-verified, that
// made the whole thing a PROXY and a weak one: with the guard deleted, execution reached readSelfIdentity
// and died on the absent DB at the ERROR check — a t.Fatalf — so the three filesystem assertions this
// file calls load-bearing never executed at all. On the real fleet shape (racknerd, where the DB exists)
// the same deletion walks all the way to render + swap + the JS-store reset, and the hermetic test's
// entire proof rested on a path that happened to point at nothing.
//
// So the DB here is REAL and seeded with this survivor's cluster_nodes row, and the nats-server stub is
// permissive. Under guard removal the function now gets as far as it would in production, and the
// filesystem assertions are the ones that fire. The "absent DB must not matter" property did not
// disappear — it moved to TestDeClusterOnAnAlreadyStandaloneConfDoesNotReadTheDB below, where it is
// asserted on its own instead of doubling as this test's detector.
func TestDeClusterOnAnAlreadyStandaloneConfWritesNothing(t *testing.T) {
	dir := t.TempDir()
	confPath := filepath.Join(dir, "nats.conf")

	if err := os.WriteFile(confPath, []byte(alreadyStandaloneConf), 0o600); err != nil {
		t.Fatal(err)
	}
	beforeStat, err := os.Stat(confPath)
	if err != nil {
		t.Fatal(err)
	}
	beforeBytes, err := os.ReadFile(confPath)
	if err != nil {
		t.Fatal(err)
	}

	// A nats-server binary that would ACCEPT anything: if the code reaches DryRun at all, the test must
	// still fail on the filesystem assertions rather than being saved by a validation error. Making the
	// stub permissive is what keeps this test about the guard and not about the validator.
	bin := filepath.Join(dir, "nats-server")
	if err := os.WriteFile(bin, []byte("#!/bin/sh\nexit 0\n"), 0o755); err != nil {
		t.Fatal(err)
	}

	// A REAL cluster_nodes row, so that deleting the guard does NOT get stopped early by a missing DB.
	// This is the production shape: the survivor has its own row, and the only thing standing between a
	// second force-single and a destructive re-render is the already-standalone branch itself.
	// It lives in a SIBLING directory on purpose: the "no unexpected file appeared" sweep below reads
	// `dir` and must stay strict, so the DB (plus sqlite's -wal/-shm) may not be allow-listed into it.
	dbDir := t.TempDir()
	dbPath := filepath.Join(dbDir, "tether.db")
	seedSelfIdentity(t, dbPath, "brk-solo", "brk-solo", "UBUSNKEYA")

	storeDir, changed, err := deClusterStandaloneConf(confPath, bin, "brk-solo", dbPath)
	if err != nil {
		t.Fatalf("an already-standalone conf must be a benign no-op, not an error: %v", err)
	}
	if changed {
		t.Error("changed=true for a conf that was already standalone — the caller then proceeds to the " +
			"JS-store reset warning path for a node that needed nothing done")
	}
	if storeDir != "/var/lib/tether/js" {
		t.Errorf("store_dir = %q, want the harvested /var/lib/tether/js (the caller needs it for the "+
			"reset warning even on the no-op path)", storeDir)
	}

	// THE LOAD-BEARING ASSERTIONS: the disk is untouched.
	afterBytes, err := os.ReadFile(confPath)
	if err != nil {
		t.Fatal(err)
	}
	if string(afterBytes) != string(beforeBytes) {
		t.Errorf("the conf was REWRITTEN on a no-op path.\n--- before ---\n%s\n--- after ---\n%s",
			beforeBytes, afterBytes)
	}
	afterStat, err := os.Stat(confPath)
	if err != nil {
		t.Fatal(err)
	}
	if !afterStat.ModTime().Equal(beforeStat.ModTime()) {
		t.Errorf("the conf's mtime moved (%v → %v) without its contents changing. The topology reconciler "+
			"uses conf mtime as its reload storm guard, so an unnecessary touch here can trigger a SIGHUP on "+
			"a node that needed nothing.", beforeStat.ModTime(), afterStat.ModTime())
	}

	// No backup may exist: Apply creates a one-time pristine .bak, so a .bak appearing proves a swap
	// happened. Checking for the artefact is stronger than trusting the return value.
	entries, err := os.ReadDir(dir)
	if err != nil {
		t.Fatal(err)
	}
	for _, e := range entries {
		if name := e.Name(); name != "nats.conf" && name != "nats-server" {
			t.Errorf("an unexpected file appeared during a no-op de-cluster: %q. natsconf.Apply keeps a "+
				"one-time .bak, so any new artefact here means the conf was swapped.", name)
		}
	}
}

// TestDeClusterOnAnAlreadyStandaloneConfDoesNotReadTheDB pins the ORDERING that the test above no longer
// depends on: the already-standalone branch must return before readSelfIdentity, so a survivor whose DB
// is missing or unreadable still gets a clean no-op rather than an error.
//
// This is a real property and not just bookkeeping — the 2026-07-04 shape is a hand-de-clustered broker,
// and an operator running force-single on it a second time from a directory where the DB has been moved
// aside must not be told the de-cluster failed. It is asserted here ALONE so that it cannot silently
// become the detector for a different defect (which is exactly what went wrong before: it fired on guard
// REMOVAL, masking the fact that the filesystem assertions never ran).
func TestDeClusterOnAnAlreadyStandaloneConfDoesNotReadTheDB(t *testing.T) {
	dir := t.TempDir()
	confPath := filepath.Join(dir, "nats.conf")
	if err := os.WriteFile(confPath, []byte(alreadyStandaloneConf), 0o600); err != nil {
		t.Fatal(err)
	}
	bin := filepath.Join(dir, "nats-server")
	if err := os.WriteFile(bin, []byte("#!/bin/sh\nexit 0\n"), 0o755); err != nil {
		t.Fatal(err)
	}

	_, changed, err := deClusterStandaloneConf(confPath, bin, "brk-solo", filepath.Join(dir, "absent.db"))
	if err != nil {
		t.Fatalf("the no-op path must not touch the DB, so an absent one must not fail it: %v", err)
	}
	if changed {
		t.Error("changed=true on an already-standalone conf")
	}
}

// TestDeClusterOnAClusteredConfDoesChangeIt is the other half. Without it the test above would pass just
// as well against a function that never does anything at all, which is the classic way an idempotence
// test becomes vacuous.
//
// It detects guard INVERSION, not guard REMOVAL — with the branch deleted, `already` is never true and
// this stays green. Removal is TestDeClusterOnAnAlreadyStandaloneConfWritesNothing's job, which is why
// that test now carries a real DB.
func TestDeClusterOnAClusteredConfDoesChangeIt(t *testing.T) {
	dir := t.TempDir()
	confPath := filepath.Join(dir, "nats.conf")
	const clusteredConf = `# tether nats-server config (generated by install.sh)
server_name: "brk-solo"
host: "0.0.0.0"
port: 4222
http: "127.0.0.1:8223"
jetstream {
  store_dir: "/var/lib/tether/js"
}
cluster {
  name: "tether"
  listen: "0.0.0.0:6222"
  routes: [
    "nats://10.0.0.2:6222"
  ]
  tls {
    ca_file: "/etc/tether/secrets/cluster-ca.pem"
    cert_file: "/etc/tether/secrets/route-cert.pem"
    key_file: "/etc/tether/secrets/route-key.pem"
    verify: true
  }
}
authorization {
  auth_callout {
    issuer: "ABROKERACCOUNTPUB"
    account: "$G"
    auth_users: [ "UBUSNKEYA" ]
  }
  users: [
    { nkey: "UBUSNKEYA" }
  ]
}
`
	if err := os.WriteFile(confPath, []byte(clusteredConf), 0o600); err != nil {
		t.Fatal(err)
	}
	own, err := natsconf.Preflight(confPath)
	if err != nil {
		t.Fatalf("fixture must preflight clean: %v", err)
	}
	if !own.IsClusteredTopology() || !own.HasJetStream() {
		t.Fatal("fixture must read as CLUSTERED topology WITH JetStream enabled, else this test proves " +
			"nothing about the difference between the two arms. Both facts are asserted separately since " +
			"RB2-1 — a fixture that satisfied only one of them would exercise a different path")
	}
	// The clustered arm needs a real cluster_nodes row to resolve its identity, which this package's
	// offline tests build elsewhere; asserting the ARM SELECTION is what matters here, so stop at the
	// point where the two paths visibly diverge: buildStandaloneConf must NOT report already=true.
	_, _, already, berr := buildStandaloneConf(confPath, "brk-solo", filepath.Join(dir, "absent.db"))
	if already {
		t.Error("a CLUSTERED conf was reported as already-standalone — the guard is inverted, and " +
			"force-single would silently skip the de-cluster it exists to perform")
	}
	if berr == nil {
		t.Log("note: buildStandaloneConf returned no error without a cluster_nodes row; the identity read " +
			"is evidently reached later than expected — not a failure of this assertion")
	}
}
